namespace Mundialito.Domain.Common;

/// <summary>
/// Base class for every persisted domain object. Identity is a time-ordered GUID (version 7),
/// generated in the domain so an entity has an id before it is ever stored.
/// </summary>
public abstract class Entity
{
    private readonly List<IDomainEvent> _domainEvents = [];

    protected Entity(Guid id)
    {
        Id = id;
    }

    /// <summary>Required by EF Core for materialization.</summary>
    protected Entity()
    {
    }

    public Guid Id { get; init; }

    public IReadOnlyCollection<IDomainEvent> DomainEvents => _domainEvents.AsReadOnly();

    public void ClearDomainEvents() => _domainEvents.Clear();

    protected void RaiseDomainEvent(IDomainEvent domainEvent) => _domainEvents.Add(domainEvent);

    protected static Guid NewId() => Guid.CreateVersion7();
}

/// <summary>
/// Entity with creation/update timestamps and an optimistic concurrency token. The timestamps are
/// stamped by Infrastructure at commit time and the token is generated by the database on every
/// write, which keeps the domain free of clock and persistence dependencies.
/// </summary>
public abstract class AuditableEntity : Entity
{
    protected AuditableEntity(Guid id)
        : base(id)
    {
    }

    protected AuditableEntity()
    {
    }

    public DateTime CreatedAtUtc { get; private set; }

    public DateTime? UpdatedAtUtc { get; private set; }

    /// <summary>
    /// Database-generated version (SQL Server rowversion). Clients receive it as an ETag and send it
    /// back in If-Match; a mismatch means someone else changed the row in between.
    /// </summary>
    public byte[]? RowVersion { get; private set; }

    public void MarkCreated(DateTime utcNow) => CreatedAtUtc = utcNow;

    public void MarkUpdated(DateTime utcNow) => UpdatedAtUtc = utcNow;

    /// <summary>True when the caller's expected version still matches the stored one.</summary>
    public bool HasVersion(ReadOnlySpan<byte> expected) =>
        RowVersion is not null && expected.SequenceEqual(RowVersion);
}
